def get_theme(name='sakura'):
    key = (name or 'sakura').strip().lower().replace('-', '_').replace(' ', '_')
    key = ALIASES.get(key, key)
    if key not in THEMES:
        raise KeyError('Unknown theme %r. Available: %s' % (name, ', '.join(sorted(THEMES))))
    t = dict(THEMES[key])
    t['id'] = key
    return t
